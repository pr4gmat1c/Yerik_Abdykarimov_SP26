-- =============================================================================
-- FCT_SALES_DD — transaction-grain fact table
-- Grain: one row per order line (one product, one customer/company, one
-- order, one date, one channel) — unchanged from the grain declared in
-- Business Template Section 1.5 / carried through BL_3NF.CE_SALES.
-- "_DD" = daily date grain (EVENT_DT holds a calendar day, not an
-- aggregated period), per Naming Conventions rule #15.
-- =============================================================================
CREATE TABLE BL_DM.FCT_SALES_DD (
    EVENT_DT                     DATE           NOT NULL,   -- FK -> DIM_DATES.DATE_KEY; the order date
    PRODUCT_SURR_ID               BIGINT         NOT NULL,   -- FK -> DIM_PRODUCTS
    CUSTOMER_SURR_ID               BIGINT         NOT NULL,   -- FK -> DIM_CUSTOMERS_SCD (logical only — no DB constraint for SCD2 dimensions, per Naming Conventions)
    EMPLOYEE_SURR_ID                BIGINT         NOT NULL,   -- FK -> DIM_EMPLOYEES (0 for B2C rows)
    CHANNEL_SURR_ID                  INT            NOT NULL,   -- FK -> DIM_CHANNELS
    PAYMENT_METHOD_SURR_ID            INT            NOT NULL,   -- FK -> DIM_PAYMENT_METHODS (0 for B2B rows)
    SHIPPING_TYPE_SURR_ID              INT            NOT NULL,   -- FK -> DIM_SHIPPING_TYPES (0 for B2B rows)
    PAYMENT_TERMS_SURR_ID               INT            NOT NULL,   -- FK -> DIM_PAYMENT_TERMS (0 for B2C rows)
    ORDER_ID                      BIGINT         NOT NULL,   -- degenerate dimension
    ORDER_STATUS                  VARCHAR(20)    NOT NULL,   -- degenerate dimension
    FCT_QUANTITY_UNT               INT            NOT NULL,
    FCT_UNIT_PRICE_AMT             NUMERIC(10,2)  NOT NULL,
    FCT_UNIT_COST_AMT              NUMERIC(10,2)  NOT NULL,
    FCT_SALES_AMT                  NUMERIC(12,2)  NOT NULL,
    FCT_COST_AMT                   NUMERIC(12,2)  NOT NULL,
    FCT_GROSS_MARGIN_AMT           NUMERIC(12,2)  NOT NULL,   -- CALCULATED: FCT_SALES_AMT - FCT_COST_AMT
    FCT_GROSS_MARGIN_PCT           NUMERIC(5,2)   NOT NULL,   -- CALCULATED: FCT_GROSS_MARGIN_AMT / FCT_SALES_AMT * 100
    RATING                        INT,                        -- B2C only
    FCT_ADD_ON_TOTAL_AMT           NUMERIC(10,2),              -- B2C only
    RETURN_OR_COMPLAINT_FLAG      VARCHAR(5),                 -- B2C only
    FEEDBACK_COMMENT              VARCHAR(255),               -- B2C only
    RESOLUTION_TIME_DAYS          INT,                        -- B2C only
    FCT_REFUND_AMOUNT_AMT          NUMERIC(10,2),              -- B2C only
    SUPPORT_CHANNEL_USED          VARCHAR(10),                -- B2C only
    ESCALATION_REQUIRED_FLAG      VARCHAR(5),                 -- B2C only
    PO_NUMBER                     VARCHAR(20),                -- B2B only (degenerate)
    PO_ISSUE_DATE                 DATE,                       -- B2B only
    REQUESTED_DELIVERY_DATE       DATE,                       -- B2B only
    APPROVAL_STATUS               VARCHAR(10),                -- B2B only
    PO_TYPE                       VARCHAR(10),                -- B2B only
    PO_VALUE_THRESHOLD_FLAG       VARCHAR(5),                 -- B2B only
    INSERT_DT                     DATE           NOT NULL
    -- No surrogate PK (per BL_3NF.CE_SALES precedent) and no UPDATE_DT
    -- (a transactional fact is never updated in place).
);

CREATE INDEX IX_FCT_SALES_DD_EVENT_DT       ON BL_DM.FCT_SALES_DD (EVENT_DT);
CREATE INDEX IX_FCT_SALES_DD_PRODUCT        ON BL_DM.FCT_SALES_DD (PRODUCT_SURR_ID);
CREATE INDEX IX_FCT_SALES_DD_CUSTOMER       ON BL_DM.FCT_SALES_DD (CUSTOMER_SURR_ID);
CREATE INDEX IX_FCT_SALES_DD_CHANNEL        ON BL_DM.FCT_SALES_DD (CHANNEL_SURR_ID);

-- Physical (enforced) FKs only where the referenced dimension is Type 1/0 --
-- never against an SCD2 dimension (Naming Conventions, "Rules for Facts
-- table" #2: creating an FK constraint against an SCD2 table is prohibited).
ALTER TABLE BL_DM.FCT_SALES_DD
    ADD CONSTRAINT FK_FCT_SALES_PRODUCT  FOREIGN KEY (PRODUCT_SURR_ID)        REFERENCES BL_DM.DIM_PRODUCTS (PRODUCT_SURR_ID),
    ADD CONSTRAINT FK_FCT_SALES_EMPLOYEE FOREIGN KEY (EMPLOYEE_SURR_ID)       REFERENCES BL_DM.DIM_EMPLOYEES (EMPLOYEE_SURR_ID),
    ADD CONSTRAINT FK_FCT_SALES_CHANNEL  FOREIGN KEY (CHANNEL_SURR_ID)        REFERENCES BL_DM.DIM_CHANNELS (CHANNEL_SURR_ID),
    ADD CONSTRAINT FK_FCT_SALES_PAYMTHD  FOREIGN KEY (PAYMENT_METHOD_SURR_ID) REFERENCES BL_DM.DIM_PAYMENT_METHODS (PAYMENT_METHOD_SURR_ID),
    ADD CONSTRAINT FK_FCT_SALES_SHIPTYP  FOREIGN KEY (SHIPPING_TYPE_SURR_ID)  REFERENCES BL_DM.DIM_SHIPPING_TYPES (SHIPPING_TYPE_SURR_ID),
    ADD CONSTRAINT FK_FCT_SALES_PAYTERM  FOREIGN KEY (PAYMENT_TERMS_SURR_ID)  REFERENCES BL_DM.DIM_PAYMENT_TERMS (PAYMENT_TERMS_SURR_ID);
-- CUSTOMER_SURR_ID -> DIM_CUSTOMERS_SCD and EVENT_DT -> DIM_DATES.DATE_KEY
-- are deliberately NOT enforced as DB constraints (SCD2 rule above; DIM_DATES
-- is created by a separate script and may not exist yet in every environment).
