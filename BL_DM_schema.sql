-- =============================================================================
-- BL_DM — NovaTech Business Layer Dimensional Model (Star Schema)
-- =============================================================================
-- This is a BONUS script, not explicitly required by the Task 4 brief (which
-- only asks for a DIM_DATES script) — provided so every table in chapter "3
-- Business Layer Dimensional Model" of the Business Template has a physical,
-- ready-to-run definition, the same way BL_3NF.* was eventually scripted.
--
-- Conventions applied throughout (see Naming_Conventions.docx):
--   - DIM_<Name in Plural>            Type 1 / Type 0 dimensions
--   - DIM_<Name in Plural>_SCD        Type 2 dimension (history tracked)
--   - FCT_<Name in Plural>_<Level>    fact table, level = DD (daily grain)
--   - <Name>_SURR_ID                  surrogate PK, generated by SEQUENCE (never SERIAL)
--   - <Name>_SRC_ID + SOURCE_SYSTEM + SOURCE_TABLE   obligatory source triplet
--   - INSERT_DT / UPDATE_DT           obligatory technical columns
--   - NOT NULL on every column except KPIs and the channel-specific
--     attributes that are genuinely inapplicable to one half of a conformed
--     dimension (flagged inline below) — the same documented exception
--     BL_3NF.CE_CUSTOMERS_SCD already uses for the identical reason.
--   - DEFAULT, UNIQUE and CHECK constraints are not used anywhere in this
--     model, mirroring the choice already made for BL_3NF.
--   - Default ("Not Applicable") rows use SURR_ID = 0, matching the
--     convention already chosen for this project at the BL_3NF layer,
--     instead of the Naming Conventions doc's generic -1 example.
-- =============================================================================

