-- =============================================================================
-- DIM_PRODUCTS  (Type 1 — overwrite; one row per SKU, conformed across B2C/B2B)
-- Hierarchy flattened from BL_3NF.CE_PRODUCTS -> CE_PRODUCT_TYPES ->
-- CE_PRODUCT_CATEGORIES into this single denormalized dimension, per
-- Naming Conventions' "Hierarchy on DM Layer" rule.
-- =============================================================================
CREATE TABLE BL_DM.DIM_PRODUCTS (
    PRODUCT_SURR_ID          BIGINT        NOT NULL,   -- PK, by sequence
    PRODUCT_SRC_ID           VARCHAR(20)   NOT NULL,    -- NK = SKU, shared by both source systems
    PRODUCT_TYPE_ID          INT           NOT NULL,    -- hierarchy level 2 (from CE_PRODUCT_TYPES)
    PRODUCT_TYPE_NAME        VARCHAR(50)   NOT NULL,
    PRODUCT_CATEGORY_ID      INT           NOT NULL,    -- hierarchy level 1, top (from CE_PRODUCT_CATEGORIES)
    PRODUCT_CATEGORY_NAME    VARCHAR(50)   NOT NULL,
    BRAND                    VARCHAR(50)   NOT NULL,
    WARRANTY_PERIOD_MONTHS   INT           NOT NULL,    -- B2C retail context; populated for every SKU (see chapter narrative)
    LAUNCH_YEAR              INT           NOT NULL,
    PRODUCT_STATUS           VARCHAR(20)   NOT NULL,
    BULK_PACKAGING_UNIT      VARCHAR(50)   NOT NULL,    -- B2B wholesale context; populated for every SKU
    MINIMUM_ORDER_QUANTITY   INT           NOT NULL,
    INSERT_DT                DATE          NOT NULL,
    UPDATE_DT                DATE          NOT NULL,
    SOURCE_SYSTEM            VARCHAR(60)   NOT NULL,
    SOURCE_TABLE             VARCHAR(60)   NOT NULL,
    CONSTRAINT PK_DIM_PRODUCTS PRIMARY KEY (PRODUCT_SURR_ID)
);

-- =============================================================================
-- DIM_CUSTOMERS_SCD  (Type 2 — account_tier and loyalty_member tracked)
-- Carries Country/City as a flattened geography hierarchy, same treatment
-- as Product above. PK is a single fresh SURR_ID per version, NOT the
-- (customer_id, start_dt) composite used at the BL_3NF layer — Naming
-- Conventions, "Rules for Facts table" #2: "As PK for SCD2 table on DM - ID
-- only."
-- =============================================================================
CREATE TABLE BL_DM.DIM_CUSTOMERS_SCD (
    CUSTOMER_SURR_ID     BIGINT        NOT NULL,   -- PK; a NEW value is generated for every version
    CUSTOMER_SRC_ID      VARCHAR(20)   NOT NULL,    -- NK; durable, same value across every version of one customer
    CUSTOMER_TYPE        VARCHAR(10)   NOT NULL,    -- 'Individual' (B2C) or 'Business' (B2B)
    CUSTOMER_NAME        VARCHAR(255),               -- Business only (NULL for Individual rows)
    DATE_OF_BIRTH        DATE,                       -- Individual only
    GENDER               VARCHAR(10),                -- Individual only
    LOYALTY_MEMBER       VARCHAR(5),                 -- Individual only; SCD2-tracked attribute
    CUSTOMER_SEGMENT     VARCHAR(20),                -- Individual only
    INDUSTRY             VARCHAR(50),                -- Business only
    ACCOUNT_TIER         VARCHAR(10),                -- Business only; SCD2-tracked attribute
    COMPANY_SIZE         VARCHAR(20),                -- Business only
    ONBOARDING_DATE      DATE,                       -- Business only
    CREDIT_LIMIT         NUMERIC(12,2),               -- Business only
    APPROVER_NAME        VARCHAR(255),               -- Business only
    BUDGET_CODE          VARCHAR(20),                -- Business only
    CITY_ID              BIGINT        NOT NULL,    -- geography hierarchy level 2 (from CE_CITIES)
    CITY_NAME            VARCHAR(100)  NOT NULL,
    COUNTRY_ID           INT           NOT NULL,    -- geography hierarchy level 1, top (from CE_COUNTRIES)
    COUNTRY_NAME         VARCHAR(100)  NOT NULL,
    START_DT             DATE          NOT NULL,
    END_DT               DATE,                       -- NULL = currently open/active version (no sentinel default; mirrors BL_3NF)
    IS_ACTIVE            VARCHAR(1)    NOT NULL,    -- 'Y' / 'N'
    INSERT_DT            DATE          NOT NULL,
    SOURCE_SYSTEM        VARCHAR(60)   NOT NULL,
    SOURCE_TABLE         VARCHAR(60)   NOT NULL,
    CONSTRAINT PK_DIM_CUSTOMERS_SCD PRIMARY KEY (CUSTOMER_SURR_ID)
    -- No UPDATE_DT: a change is always captured as a new row (see Naming
    -- Conventions SCD2 rules); same exception already used on BL_3NF.CE_CUSTOMERS_SCD.
);

